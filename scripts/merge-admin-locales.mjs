function deepEs(obj, ptObj) {
  if (typeof ptObj !== "object" || ptObj === null) return;
  for (const k of Object.keys(ptObj)) {
    if (typeof ptObj[k] === "object" && ptObj[k] !== null && !Array.isArray(ptObj[k])) {
      if (!obj[k]) obj[k] = {};
      deepEs(obj[k], ptObj[k]);
    }
  }
}
